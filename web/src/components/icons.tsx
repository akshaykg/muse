/** Default Project Icon when no project-specific favicon exists */
export function DefaultProjectIcon({ name, size = 40, className = "" }: { name: string; size?: number; className?: string }) {
  // Generate consistent subtle accent tone from project name
  const charCode = name.charCodeAt(0) || 65;
  const hue = (charCode * 37) % 360;
  return (
    <span
      className={`relative inline-flex shrink-0 items-center justify-center overflow-hidden rounded-lg border border-border bg-gradient-to-br from-surface to-background shadow-surface ${className}`}
      style={{ width: size, height: size }}
      aria-hidden="true"
    >
      <svg width={size * 0.6} height={size * 0.6} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.75" strokeLinecap="round" strokeLinejoin="round" className="text-primary">
        <path d="M21 16V8a2 2 0 0 0-1-1.73l-7-4a2 2 0 0 0-2 0l-7 4A2 2 0 0 0 3 8v8a2 2 0 0 0 1 1.73l7 4a2 2 0 0 0 2 0l7-4A2 2 0 0 0 21 16z" />
        <polyline points="3.27 6.96 12 12.01 20.73 6.96" />
        <line x1="12" y1="22.08" x2="12" y2="12" />
      </svg>
      <span
        className="absolute bottom-0 right-0 h-2 w-2 rounded-full border border-surface"
        style={{ backgroundColor: `hsl(${hue}, 70%, 50%)` }}
      />
    </span>
  );
}

